def normalize(s):
    """把 OCR 异体省略号、杂点统一成规范中文省略号。"""
    if not s:
        return s
    s = s.replace("⋯", "…").replace("•", "…").replace("„", "…")
    s = re.sub(r"\.+…+", "……", s)
    s = re.sub(r"…+", "……", s)
    s = re.sub(r"…+\.+", "……", s)
    s = re.sub(r"\.{2,}", "……", s)
    return s.strip()


def validate(data):
    """构建前的硬校验：释义不允许为空/残缺，也不允许残留 OCR 异体字符。"""
    problems = []
    for it in data:
        g = (it.get("gloss") or "").strip()
        p = it.get("pattern") or ""
        if not g:
            problems.append(f"句式 {it['num']:03d} 缺中文释义")
        if g.count("（") != g.count("）"):
            problems.append(f"句式 {it['num']:03d} 释义括号不配对: {g}")
        if re.match(r"^[）】]", g):
            problems.append(f"句式 {it['num']:03d} 释义被截断: {g}")
        if re.search(r"[【（⋯…]\s*$", p):
            problems.append(f"句式 {it['num']:03d} 标题尾部有未闭合的中文: {p}")
        for i, e in enumerate(it["examples"]):
            cn = (e.get("cn") or "").strip()
            if not cn:
                problems.append(f"句式 {it['num']:03d} 例句 {i + 1} 缺中文译文")
        for field, val in [("gloss", g)] + [
            (f"ex{i + 1}.cn", (e.get("cn") or ""))
            for i, e in enumerate(it["examples"])
        ]:
            if re.search(r"[⋯•„]", val):
                problems.append(f"句式 {it['num']:03d} {field} 残留 OCR 异体字符")
    return problems


def main():
    paths = sys.argv[1:]
    if not paths:
        root = Path(__file__).resolve().parent.parent
        paths = [str(root / "data.json")]
    for p in paths:
        data = json.loads(Path(p).read_text(encoding="utf-8"))
        ng = ne = np = nr = nclean = 0
        for it in data:
            n = it["num"]
            # 部分标题尾部粘了中文释义的省略号（OCR 错行的轻度版本）
            cleaned = re.sub(r"[…⋯•]+\s*$", "", it["pattern"]).strip()
            if cleaned != it["pattern"]:
                it["pattern"] = cleaned
                nclean += 1
            if n in GLOSS_FIX and not (it.get("gloss") or "").strip():
                it["gloss"] = GLOSS_FIX[n]
                ng += 1
            if n in PATTERN_FIX:
                it["pattern"] = PATTERN_FIX[n]
                np += 1
            if n in GLOSS_REPAIR:
                it["gloss"] = GLOSS_REPAIR[n]
                nr += 1
            it["gloss"] = normalize(it.get("gloss"))
            for i, e in enumerate(it["examples"]):
                key = (n, i)
                if key in EXAMPLE_FIX and not (e.get("cn") or "").strip():
                    e["cn"] = EXAMPLE_FIX[key]
                    ne += 1
                e["cn"] = normalize(e.get("cn"))
        problems = validate(data)
        if problems:
            print(f"[FAIL] {p}: {len(problems)} 处问题", file=sys.stderr)
            for x in problems[:20]:
                print("   ", x, file=sys.stderr)
            sys.exit(1)
        Path(p).write_text(
            json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
        print(
            f"[OK] {p}: 回填句式 {ng} 条 / 例句 {ne} 条，"
            f"修复标题 {np} 条 / 残缺释义 {nr} 条，共 {len(data)} 个句式，校验通过"
        )


if __name__ == "__main__":
    main()
